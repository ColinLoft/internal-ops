import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const sources = [
  '20261107160000_live_company_collaboration.sql',
  '20261110150000_flown_systems.sql',
  '20261114110000_multi_system_operations.sql',
  '20261115100000_company_crm.sql',
  '20261115110000_retire_company_ideas.sql',
  '20261115120000_contract_placement_and_countersigning.sql',
  '20261115130000_support_email_queue.sql',
  '20261116100000_outlook_support.sql',
  '20261117100000_security_access_boundaries.sql',
];
const header = `-- Flown Ops workspace update: run this entire file against an existing workspace.
-- WARNING: permanently deletes all Ideas, votes and discussions. Back up first.
-- Existing CRM, contracts and support foundation migrations are required.
-- Generated by node scripts/build-workspace-update.mjs; edit source migrations, not this file.
-- This manual bundle does not register Supabase CLI migration history.
begin;
do $$
begin
  if to_regclass('public.profiles') is null then
    raise exception 'Missing prerequisite public.profiles. Apply the workspace foundation first.';
  end if;
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'profiles' and column_name = 'account_status'
  ) then
    raise exception 'Missing prerequisite profiles.account_status. Apply the staff account-status migration first.';
  end if;
end;
$$;
`;
const sections = sources.map(name => {
  const path = `supabase/migrations/${name}`;
  const sql = readFileSync(new URL(path, root), 'utf8').trimEnd();
  return `-- BEGIN ${path}\n${sql}\n-- END ${path}`;
});
writeFileSync(new URL('supabase/flown_ops_update_all.sql', root), `${header}\n${sections.join('\n\n')}\n\nnotify pgrst, 'reload schema';\ncommit;\n`);
console.log(`Generated workspace SQL bundle from ${sources.length} migrations. Ideas retirement is destructive.`);
