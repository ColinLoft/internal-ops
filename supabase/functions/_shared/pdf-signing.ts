import { PDFDocument, StandardFonts, rgb } from 'npm:pdf-lib@1.17.1';

export const sha256Hex = async (value: Uint8Array) =>
  [...new Uint8Array(await crypto.subtle.digest('SHA-256', ownedBuffer(value)))]
    .map((byte) => byte.toString(16).padStart(2, '0')).join('');

const ownedBuffer = (value: Uint8Array) => {
  const buffer = new ArrayBuffer(value.byteLength);
  new Uint8Array(buffer).set(value);
  return buffer;
};

export const decodePngSignature = (dataUrl: string) => {
  if (!dataUrl.startsWith('data:image/png;base64,') || dataUrl.length > 700_000) {
    throw new Error('A PNG signature is required and must be 512 KB or smaller.');
  }
  const bytes = Uint8Array.from(atob(dataUrl.slice('data:image/png;base64,'.length)), (character) => character.charCodeAt(0));
  if (
    bytes.length > 512 * 1024
    || bytes[0] !== 0x89
    || bytes[1] !== 0x50
    || bytes[2] !== 0x4e
    || bytes[3] !== 0x47
  ) {
    throw new Error('The signature image is invalid or too large.');
  }
  return bytes;
};

export const appendSignaturePage = async (
  originalBytes: Uint8Array,
  options: { title: string; version: string; signedName: string; signaturePng?: Uint8Array; signatureLabel?: string },
) => {
  const pdf = await PDFDocument.load(originalBytes);
  if (pdf.getPageCount() > 500) throw new Error('The PDF has too many pages to sign.');
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const page = pdf.addPage([612, 792]);
  const timestamp = new Date();
  page.drawText(options.signatureLabel || 'Electronic signature', {
    x: 54, y: 720, size: 18, font, color: rgb(0.08, 0.12, 0.2),
  });
  page.drawText(`Document: ${options.title.slice(0, 150)}`, { x: 54, y: 680, size: 11, font });
  page.drawText(`Version: ${options.version}`, { x: 54, y: 658, size: 11, font });
  page.drawText(`Name: ${options.signedName}`, { x: 54, y: 632, size: 12, font });
  page.drawText(`Signed at (UTC): ${timestamp.toISOString()}`, { x: 54, y: 610, size: 10, font });
  if (options.signaturePng) {
    const image = await pdf.embedPng(options.signaturePng);
    const dimensions = image.scale(Math.min(1, 200 / image.width, 72 / image.height));
    page.drawImage(image, { x: 54, y: 520, width: dimensions.width, height: dimensions.height });
  }
  page.drawText('This signature record was generated by the workspace signing service.', {
    x: 54, y: 490, size: 9, font, color: rgb(0.3, 0.34, 0.4),
  });
  return { bytes: new Uint8Array(await pdf.save()), signedAt: timestamp.toISOString() };
};
